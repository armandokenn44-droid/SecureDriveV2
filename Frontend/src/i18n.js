export function getLang() {
  return localStorage.getItem("sd_lang") === "fr" ? "fr" : "en";
}

export function setLang(lang) {
  localStorage.setItem("sd_lang", lang === "fr" ? "fr" : "en");
  window.dispatchEvent(new Event("sd-lang-change"));
}

export function t(key) {
  const lang = getLang();
  return translations[lang][key] || translations.en[key] || key;
}